// 문자열로 적은 내용을 객체로 바꾸고, 단계마다 고유 번호를 붙인다.
(function () {
  Object.keys(window.LANGS).forEach(function (code) {
    var L = window.LANGS[code]; L.code = code; L.stages = [];
    L.units.forEach(function (u, ui) {
      u.stages.forEach(function (s, si) {
        s.id = code + '-' + (ui + 1) + '-' + (si + 1);
        s.unit = ui; s.idx = L.stages.length; s.lang = code;
        s.items = s.items.trim().split('\n').map(function (line) {
          var f = line.split('|');
          return { t: f[0], r: f[1] || '', k: f[2] || '', e: f[3] || '', alt: f[4] ? f[4].split(',') : [], lang: code, sid: s.id, kana: !!s.kana };
        });
        s.sents = (s.sents || '').trim().split('\n').filter(Boolean).map(function (line) {
          var f = line.split('|'), w = f[0].split('/');
          return { w: w, t: w.join(L.sep).replace(/ ([,.?!])/g, '$1').replace(/ ,/g, ','), k: f[1], lang: code, sid: s.id };
        });
        L.stages.push(s);
      });
    });
  });
})();
